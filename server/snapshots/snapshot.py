"""Snapshot / recovery for the computer registry + Kanban board.

A snapshot is a point-in-time copy of the two local JSON stores
that define the office's working state:

* the computer registry (``data/computers.json``), and
* the Kanban board (``data/kanban.json``),

plus an optional caller-supplied ``device_state`` dict (for
example a bridge status summary). The snapshot file lives in
``data/snapshots/<id>.json`` and holds the copied state itself —
not a pointer to it — so restoring works even after the live
files have been overwritten.

What this module deliberately does NOT do
-----------------------------------------
* It does not import any device bridge and never touches a live
  device. ``device_state`` is data handed in by the caller; the
  snapshot records it, restore hands it back in the summary, and
  nothing here acts on it.
* It does not snapshot chat history, memory (SQLite), or mail
  drafts. Those are separate stores with their own formats; a
  snapshot that silently omitted them would be a lie, so the
  manifest lists exactly which files were copied.
* Restore is explicit and audited: every restore appends a line
  to ``data/snapshots/audit.jsonl``. Restore never deletes a
  snapshot, and a file that was absent at snapshot time is left
  alone on restore (reported as skipped, not silently created).

Files are written atomically (tmp + replace), the same pattern as
``office/kanban.py`` and ``computers/registry.py``.
"""

from __future__ import annotations

import copy
import json
import os
import threading
from datetime import datetime, timezone
from pathlib import Path

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SNAPSHOTS_DIR = os.path.join(_REPO_ROOT, "data", "snapshots")
DEFAULT_COMPUTERS_FILE = os.path.join(_REPO_ROOT, "data", "computers.json")
DEFAULT_KANBAN_FILE = os.path.join(_REPO_ROOT, "data", "kanban.json")

# The stores a snapshot covers: (manifest key, default path).
SNAPSHOT_FILES = (
    ("computers.json", DEFAULT_COMPUTERS_FILE),
    ("kanban.json", DEFAULT_KANBAN_FILE),
)

MAX_DEVICE_STATE_CHARS = 65536


def _utcnow():
    return datetime.now(timezone.utc)


def _iso(dt):
    return dt.isoformat(timespec="seconds")


def _atomic_write(path, text):
    tmp = str(path) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def _read_json_file(path):
    """Parsed JSON of a store file, or None when missing/unreadable.

    A corrupt live file snapshots as None (reported in the manifest
    as ``present: False``) rather than failing the whole snapshot:
    the snapshot's job is to record what existed, honestly.
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, dict):
            return None
        return data
    except (OSError, ValueError):
        return None


class SnapshotStore:
    """Snapshots of the registry + Kanban state, one file each."""

    def __init__(self, snapshots_dir=None, computers_file=None,
                 kanban_file=None):
        self.dir = Path(snapshots_dir or os.environ.get(
            "GROKBOT_SNAPSHOTS_DIR", DEFAULT_SNAPSHOTS_DIR))
        self.dir.mkdir(parents=True, exist_ok=True)
        self.computers_file = computers_file or os.environ.get(
            "GROKBOT_COMPUTERS_FILE", DEFAULT_COMPUTERS_FILE)
        self.kanban_file = kanban_file or os.environ.get(
            "GROKBOT_KANBAN_FILE", DEFAULT_KANBAN_FILE)
        self._lock = threading.Lock()
        self.audit_path = self.dir / "audit.jsonl"

    def _snapshot_path(self, snapshot_id):
        # Ids are generated by this module (snap-N); reject any id
        # containing a path separator so a crafted id can never
        # escape the snapshots directory.
        if (not isinstance(snapshot_id, str) or not snapshot_id
                or "/" in snapshot_id or "\\" in snapshot_id
                or snapshot_id in (".", "..")):
            raise ValueError("invalid snapshot id %r" % (snapshot_id,))
        return self.dir / ("%s.json" % snapshot_id)

    def _next_id_locked(self):
        # A persistent counter (not derived from the files on disk),
        # so an id is never reused after its snapshot is deleted.
        counter_path = self.dir / "counter.json"
        try:
            with open(counter_path, "r", encoding="utf-8") as f:
                counter = json.load(f)
            nxt = int(counter.get("next", 1))
        except (OSError, ValueError, TypeError):
            nxt = 1
        snapshot_id = "snap-%d" % nxt
        _atomic_write(counter_path, json.dumps(
            {"next": nxt + 1}, indent=2, ensure_ascii=False))
        return snapshot_id

    def _audit(self, event, snapshot_id, detail=None):
        entry = {"event": event, "snapshot_id": snapshot_id,
                 "at": _iso(_utcnow()), "detail": detail or {}}
        with open(self.audit_path, "a", encoding="utf-8") as f:
            f.write(json.dumps(entry, ensure_ascii=False) + "\n")

    # -- public API -------------------------------------------------
    def create_snapshot(self, device_state=None) -> dict:
        """Copy registry + Kanban state into ``data/snapshots/``.

        ``device_state`` (optional dict) is stored verbatim; it is
        caller data, never fetched from a device here. Returns the
        manifest (a copy): ``{id, created_at, files, device_state}``.
        """
        if device_state is not None:
            if not isinstance(device_state, dict):
                raise ValueError("device_state must be a dict")
            if len(json.dumps(device_state, ensure_ascii=False)) \
                    > MAX_DEVICE_STATE_CHARS:
                raise ValueError("device_state is too large")
        with self._lock:
            snapshot_id = self._next_id_locked()
            now = _iso(_utcnow())
            sources = {"computers.json": self.computers_file,
                       "kanban.json": self.kanban_file}
            files = {}
            contents = {}
            for name, path in sources.items():
                data = _read_json_file(path)
                contents[name] = data
                files[name] = {
                    "present": data is not None,
                    "source": str(path),
                }
            manifest = {
                "id": snapshot_id,
                "created_at": now,
                "files": files,
                "file_names": sorted(files),
                "device_state": copy.deepcopy(device_state),
                "state": contents,
            }
            _atomic_write(self._snapshot_path(snapshot_id),
                          json.dumps(manifest, indent=2,
                                     ensure_ascii=False))
            self._audit("created", snapshot_id,
                        {"files": sorted(files)})
            return copy.deepcopy(manifest)

    def list_snapshots(self) -> list:
        """Summaries of all snapshots, oldest first.

        A file that is not valid snapshot JSON is listed with
        ``ok: False`` and its parse error, never hidden.
        """
        summaries = []
        for path in sorted(self.dir.glob("snap-*.json")):
            try:
                with open(path, "r", encoding="utf-8") as f:
                    manifest = json.load(f)
                if not isinstance(manifest, dict):
                    raise ValueError("snapshot is not a JSON object")
                summaries.append({
                    "id": manifest.get("id", path.stem),
                    "created_at": manifest.get("created_at"),
                    "files": manifest.get("file_names", []),
                    "has_device_state":
                        manifest.get("device_state") is not None,
                    "ok": True,
                })
            except (OSError, ValueError) as e:
                summaries.append({
                    "id": path.stem, "created_at": None, "files": [],
                    "has_device_state": False, "ok": False,
                    "error": str(e),
                })
        summaries.sort(key=lambda s: (s["created_at"] or "", s["id"]))
        return summaries

    def get_snapshot(self, snapshot_id) -> dict | None:
        """Full manifest for one snapshot, or None if missing."""
        path = self._snapshot_path(snapshot_id)
        try:
            with open(path, "r", encoding="utf-8") as f:
                manifest = json.load(f)
        except (OSError, ValueError):
            return None
        if not isinstance(manifest, dict):
            return None
        return copy.deepcopy(manifest)

    def restore_snapshot(self, snapshot_id) -> dict:
        """Write the snapshot's stored state back, atomically.

        Returns ``{id, restored, skipped, device_state}``:
        ``restored`` lists the store files rewritten, ``skipped``
        lists files that were absent at snapshot time (left alone),
        and ``device_state`` is the stored dict handed back to the
        caller — nothing here acts on it. The restore is audited.

        Raises KeyError for an unknown snapshot id, ValueError for
        a corrupt snapshot file.
        """
        with self._lock:
            manifest = self.get_snapshot(snapshot_id)
            if manifest is None:
                raise KeyError("unknown snapshot %r" % snapshot_id)
            state = manifest.get("state")
            if not isinstance(state, dict):
                raise ValueError(
                    "snapshot %s is corrupt: no stored state"
                    % snapshot_id)
            targets = {"computers.json": self.computers_file,
                       "kanban.json": self.kanban_file}
            restored, skipped = [], []
            for name, target in targets.items():
                data = state.get(name)
                if data is None:
                    skipped.append(name)
                    continue
                target_path = Path(target)
                if target_path.parent:
                    target_path.parent.mkdir(parents=True, exist_ok=True)
                _atomic_write(target_path, json.dumps(
                    data, indent=2, ensure_ascii=False))
                restored.append(name)
            self._audit("restored", snapshot_id,
                        {"restored": restored, "skipped": skipped})
            return {"id": snapshot_id,
                    "restored": restored,
                    "skipped": skipped,
                    "device_state": copy.deepcopy(
                        manifest.get("device_state"))}

    def delete_snapshot(self, snapshot_id) -> bool:
        """Delete a snapshot file. Returns True if one was removed.

        Raises KeyError for an unknown id (a silent no-op would
        hide a typo'd id).
        """
        with self._lock:
            path = self._snapshot_path(snapshot_id)
            if not path.is_file():
                raise KeyError("unknown snapshot %r" % snapshot_id)
            path.unlink()
            self._audit("deleted", snapshot_id)
            return True
